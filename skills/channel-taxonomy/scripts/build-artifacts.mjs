import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { TAXONOMY_VERSION } from './channel-taxonomy.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.join(here, 'channel-taxonomy.mjs');
const outputPath = path.join(here, '..', 'references', 'sql', 'classify_channels.sql');

function implementationSource(source) {
  return source
    .replace(/^\/\*[\s\S]*?\*\/\s*/m, '')
    .replace(/\nexport \{[\s\S]*?\};?\s*$/m, '\n')
    .trim();
}

function sqlFor(source) {
  return `-- Generated by skills/channel-taxonomy/scripts/build-artifacts.mjs.\n-- Taxonomy version: ${TAXONOMY_VERSION}\n-- Run this file as a standalone BigQuery script; it reads no customer tables.\nCREATE TEMP FUNCTION classify_channel(input_json STRING)\nRETURNS STRING\nLANGUAGE js\nAS r'''\n${source}\nreturn classifyChannel(JSON.parse(input_json));\n''';\n\nWITH synthetic AS (\n  SELECT 'paid-click' AS case_id, '{"utm_source":"google","utm_medium":"cpc","landing_url":"https://example.test/?gclid=abc"}' AS input_json UNION ALL\n  SELECT 'email', '{"utm_medium":"email"}' UNION ALL\n  SELECT 'direct', '{"landing_url":"https://example.test/landing"}' UNION ALL\n  SELECT 'other', '{"utm_source":"mystery"}'\n)\nSELECT case_id, classify_channel(input_json) AS channel\nFROM synthetic\nORDER BY case_id;\n`;
}

const source = await readFile(sourcePath, 'utf8');
const implementation = implementationSource(source);
const ids = ['gclid', 'dclid', 'gbraid', 'wbraid', 'msclkid', 'fbclid', 'ttclid', 'rdt_cid', 'li_fat_id', 'twclid', 'epik', 'sccid', 'srsltid'];
// Reuse the canonical URL helpers, including fragment exclusion and encoded query keys.
const clickParser = `CREATE TEMP FUNCTION extract_landing_click_ids(landing_url STRING)
RETURNS STRUCT<${ids.map((id) => `${id} STRING`).join(', ')}>
LANGUAGE js
AS r'''
${implementation}
const params = hostOf(landing_url) ? queryParams(landing_url) : {};
const result = {};
${JSON.stringify(ids)}.forEach((id) => { result[id] = params[id] === undefined ? null : params[id]; });
return result;
''';`;
const udf = sqlFor(implementation).split('\n\nWITH synthetic AS (')[0] + '\n\n' + clickParser;
const artifacts = new Map([[outputPath, sqlFor(implementation)]]);
// A standalone install only regenerates its own reference UDF.
if (process.argv.includes('--repository')) {
  const skillsRoot = path.resolve(here, '../..');
  for (const skill of ['ga4-bigquery-export', 'first-party-pixel']) {
    await readFile(path.join(skillsRoot, skill, 'SKILL.md'), 'utf8');
  }
  const contract = await readFile(path.join(here, '../references/channel-contract.md'), 'utf8');
  const sessionCtes = await readFile(path.join(skillsRoot, 'ga4-bigquery-export/scripts/session-ctes.sql'), 'utf8');
  artifacts.set(path.join(skillsRoot, 'first-party-pixel/assets/collector/channel-taxonomy.mjs'), source);
  for (const skill of ['ga4-bigquery-export', 'first-party-pixel']) {
    artifacts.set(path.join(skillsRoot, skill, 'references/channel-contract.md'), contract);
  }
  function replaceBlock(sql, name, body) {
    const begin = `-- BEGIN GENERATED ${name}`;
    const end = `-- END GENERATED ${name}`;
    if (!sql.includes(begin) || !sql.includes(end)) throw new Error(`Missing ${name} markers`);
    return sql.slice(0, sql.indexOf(begin)) + begin + '\n' + body.trimEnd() + '\n' + sql.slice(sql.indexOf(end));
  }
  for (const name of ['sessions.sql', 'channel_daily.sql']) {
    const target = path.join(skillsRoot, 'ga4-bigquery-export/references/sql', name);
    let sql = await readFile(target, 'utf8');
    sql = replaceBlock(sql, 'CHANNEL TAXONOMY', udf.replace('-- Run this file as a standalone BigQuery script; it reads no customer tables.\n', ''));
    sql = replaceBlock(sql, 'SESSION CTES', sessionCtes.replaceAll('{{TAXONOMY_VERSION}}', TAXONOMY_VERSION));
    artifacts.set(target, sql);
  }
}
const check = process.argv.includes('--check');
for (const [target, output] of artifacts) {
  if (check) {
    const existing = await readFile(target, 'utf8').catch(() => '');
    if (existing !== output) {
      console.error(`Generated artifact is stale: ${path.relative(process.cwd(), target)}`);
      process.exitCode = 1;
    }
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, output);
    console.log(`Wrote ${path.relative(process.cwd(), target)}`);
  }
}
